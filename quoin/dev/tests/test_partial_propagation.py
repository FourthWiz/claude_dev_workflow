# HOP 4: dashboard_server.py /api/tasks* json.dumps pass-through
# ---------------------------------------------------------------------------

def test_hop4_api_tasks_json_carries_partial_true(tmp_path):
    """A hypothetical server-side cost-key re-filter would fail HERE."""
    project_root = _make_mixed_project(tmp_path)
    empty_home = tmp_path / "empty-home"
    provider = make_cost_provider(project_root, home=empty_home)

    server, _ = _start_server(project_root, provider)
    try:
        status, body = _get(server, "/api/tasks")
        assert status == 200
        payload = json.loads(body)
        tasks = {t["name"]: t for t in payload["tasks"]}
        assert tasks["mixed-task"]["cost"]["partial"] is True, (
            "HOP 4 FAILED: /api/tasks JSON body dropped 'partial' on the wire"
        )

        status2, body2 = _get(server, "/api/tasks/mixed-task")
        assert status2 == 200
        detail_payload = json.loads(body2)
        assert detail_payload["cost"]["partial"] is True, (
            "HOP 4 FAILED: /api/tasks/<name> JSON body dropped 'partial' on the wire"
        )
    finally:
        server.shutdown()


def test_hop4_resolved_zero_survives_to_json(tmp_path):
    """MINOR-5/D-8 corollary at HOP 4: a resolved usd=0.0 must reach the wire
    as mode=usd/usd=0.0, not None/counts."""
    project_root = _make_resolved_zero_project(tmp_path)
    empty_home = tmp_path / "empty-home"
    provider = make_cost_provider(project_root, home=empty_home)

    server, _ = _start_server(project_root, provider)
    try:
        status, body = _get(server, "/api/tasks/zero-task")
        assert status == 200
        payload = json.loads(body)
        assert payload["cost"]["mode"] == "usd"
        assert payload["cost"]["usd"] == 0.0
        assert payload["cost"]["partial"] is False
    finally:
        server.shutdown()


