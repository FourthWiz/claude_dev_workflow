def test_hop123_scan_tasks_emits_partial_true_for_mixed_ledger(tmp_path):
    """A drop at HOP 2 (removing 'partial' from the dashboard_model merge
    whitelist) fails HERE — this asserts through the emitted scan_tasks dict,
    not the provider's raw return."""
    project_root = _make_mixed_project(tmp_path)
    empty_home = tmp_path / "empty-home"  # no JSONL tree — proves inline path
    provider = make_cost_provider(project_root, home=empty_home)

    result = scan_tasks(project_root, cost_provider=provider)
    tasks = {t["name"]: t for t in result["tasks"]}
    assert "mixed-task" in tasks
    cost = tasks["mixed-task"]["cost"]
    assert cost["mode"] == "usd"
    assert cost["usd"] == pytest.approx(1.25)
    assert cost["partial"] is True, (
        "HOP 2/3 FAILED: 'partial' did not survive dashboard_model._task_summary "
        "into the scan_tasks-emitted cost dict"
    )


def test_hop123_task_detail_emits_partial_true_for_mixed_ledger(tmp_path):
    project_root = _make_mixed_project(tmp_path)
    empty_home = tmp_path / "empty-home"
    provider = make_cost_provider(project_root, home=empty_home)

    detail = task_detail(project_root, "mixed-task", cost_provider=provider)
    assert detail["cost"]["partial"] is True, "HOP 2/3 FAILED at task_detail"
    assert detail["cost"]["usd"] == pytest.approx(1.25)


