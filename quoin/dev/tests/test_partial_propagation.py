def _make_mixed_project(tmp_path: Path, task_name: str = "mixed-task") -> Path:
    project_root = tmp_path / "project"
    task_dir = project_root / ".workflow_artifacts" / task_name
    task_dir.mkdir(parents=True)
    ledger = task_dir / "cost-ledger.md"
    ledger.write_text(
        "# Cost Ledger — mixed-task\n"
        "res-uuid-0001 | 2026-07-27 | implement | opus | task | \"resolved\" | 0 | "
        "usd=1.25;tok=1000;src=nested_jsonl\n"
        "unres-uuid-0002 | 2026-07-27 | implement | opus | task | \"unresolved\" | 0 | "
        "tok=45;src=unresolved\n"
    )
    return project_root


def _make_resolved_zero_project(tmp_path: Path, task_name: str = "zero-task") -> Path:
    """MINOR-5/D-8 corollary fixture: a single resolved usd=0.0 row."""
    project_root = tmp_path / "project"
    task_dir = project_root / ".workflow_artifacts" / task_name
    task_dir.mkdir(parents=True)
    ledger = task_dir / "cost-ledger.md"
    ledger.write_text(
        "# Cost Ledger — zero-task\n"
        "zero-uuid-0001 | 2026-07-27 | implement | opus | task | \"resolved zero\" | 0 | "
        "usd=0.0;tok=9;src=nested_jsonl\n"
    )
    return project_root


def _start_server(project_root: Path, cost_provider):
    """Start dashboard_server in a background thread. Returns (server, thread)."""
    class _Handler(_dashboard_server.DashboardHandler):
        pass

    _Handler.project_root = project_root
    # staticmethod() is REQUIRED here — see dashboard_server.py's DashboardHandler
    # NOTE (T-12 fix): a bare function assigned to a class attribute auto-binds
    # as a method via self.cost_provider, injecting an extra `self` arg and
    # raising on every call (silently swallowed, degrading to counts-mode).
    _Handler.cost_provider = staticmethod(cost_provider)

    server = _dashboard_server.DashboardServer(("127.0.0.1", 0), _Handler)
    t = threading.Thread(target=server.serve_forever, daemon=True)
    t.start()
    return server, t


def _get(server, path: str):
    port = server.server_address[1]
    conn = http.client.HTTPConnection("127.0.0.1", port, timeout=5)
    conn.request("GET", path)
    resp = conn.getresponse()
    body = resp.read()
    conn.close()
    return resp.status, body


