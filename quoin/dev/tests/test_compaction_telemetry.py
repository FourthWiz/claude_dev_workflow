# ─── ambiguity / tie-break unit ──────────────────────────────────────────────


def test_ambiguity_tie_break_rotation_fixture(tmp_path):
    """Drives the (T-01-rotate) shape: four compactions under a small
    QUOIN_TELEMETRY_MAX_BYTES so the sink rotates. The per-file tie-break
    resolves the guaranteed same-key collision without cross-file merging
    (round-1 critic MAJ-4) — round-3 critic MIN-1: only pairs 3 and 4
    survive on disk (mv -f overwrites .1 each time), so matched == 2."""
    transcript = tmp_path / "dummy.jsonl"
    transcript.write_text('{"type":"message"}\n')
    env = {"QUOIN_TELEMETRY_MAX_BYTES": "200"}
    for _ in range(4):
        _drive_pair(tmp_path, "sess-rotate", transcript, env=env)

    report = _run_reader(tmp_path)
    assert report["ambiguous"] == 0
    assert report["matched"] == 2


def test_ambiguity_hand_authored_collision(tmp_path):
    """A same-file (session_id, event_seq) collision the hooks themselves
    can also produce once QUOIN_TELEMETRY_MAX_BYTES exceeds the 1 MiB tail
    window (round-2 critic MIN-3) — hand-authored here for fixture
    convenience, not because it is hook-impossible."""
    tel_dir = tmp_path / ".workflow_artifacts" / "memory" / "telemetry"
    tel_dir.mkdir(parents=True)
    sink = tel_dir / "compaction-events.jsonl"
    records = [
        {"v": 1, "half": "pre", "session_id": "sess-collide", "event_seq": 0, "ts": "2026-01-01T00:00:00Z"},
        {"v": 1, "half": "pre", "session_id": "sess-collide", "event_seq": 0, "ts": "2026-01-01T00:00:01Z"},
        {"v": 1, "half": "post", "session_id": "sess-collide", "event_seq": 0, "ts": "2026-01-01T00:00:02Z"},
        {"v": 1, "half": "pre", "session_id": "sess-collide", "event_seq": 1, "ts": "2026-01-01T00:00:03Z"},
        {"v": 1, "half": "post", "session_id": "sess-collide", "event_seq": 1, "ts": "2026-01-01T00:00:04Z"},
    ]
    sink.write_text("\n".join(json.dumps(r) for r in records) + "\n")

    report = _run_reader(tmp_path)
    assert report["ambiguous"] == 3
    assert report["matched"] == 1
    assert report["pre_only"] == 0
    assert report["post_only"] == 0


# ─── end-to-end pair with a planted run-state record ─────────────────────────

_JQ_MISSING = pytest.mark.skipif(
    __import__("shutil").which("jq") is None, reason="jq required by the hooks"
)


@_JQ_MISSING
def test_end_to_end_pair_with_run_state(tmp_path):
    transcript = tmp_path / "dummy.jsonl"
    transcript.write_text('{"type":"message"}\n')

    subprocess.run(
        [
            PY, str(RUN_STATE), "--write", "--project-root", str(tmp_path),
            "--task", "tel-e2e", "--session-id", "sess-tel-e2e",
            "--phase", "implement", "--subphase", "code", "--step", "e2e step",
        ],
        capture_output=True, text=True, timeout=15,
    )
    _drive_pair(tmp_path, "sess-tel-e2e", transcript)

    sink = _sink_path(tmp_path)
    lines = [json.loads(l) for l in sink.read_text().splitlines() if l.strip()]
    pre = next(r for r in lines if r["half"] == "pre")
    post = next(r for r in lines if r["half"] == "post")
    assert pre["session_id"] == post["session_id"] == "sess-tel-e2e"
    assert pre["event_seq"] == post["event_seq"]
    assert pre["task"] == "tel-e2e"
    assert pre["phase"] == "implement"
    assert pre["subphase"] == "code"
    assert pre["step"] == "e2e step"

    report = _run_reader(tmp_path)
    assert report["matched"] == 1
    assert report["by_task"].get("tel-e2e") == 1


# ─── hook source contract (environment-independent) ──────────────────────────


def _postcompact_text() -> str:
    return HOOK_POST.read_text()


def _precompact_text() -> str:
    return HOOK_PRE.read_text()


def test_postcompact_source_contract():
    text = _postcompact_text()
    assert '--arg half "post"' in text
    assert "read_constants" in text
    # No printf line interpolates $session_id directly into a hand-built
    # `{`-shaped JSON string — every emitted value goes through jq --arg.
    for line in text.splitlines():
        if "printf" in line and "{" in line and "$session_id" in line:
            pytest.fail(f"hand-built JSON interpolating $session_id: {line!r}")
    # .allow-compact check precedes the rest of STEP 3's work.
    step3_idx = text.index("# STEP 3: Telemetry")
    marker_idx = text.index('[ -f "${cwd}/.allow-compact" ] && exit 0')
    assert marker_idx > step3_idx, "marker check must be inside/after STEP 3's own comment"
    # it must be the FIRST statement inside the STEP 3 subshell body
    subshell_open_idx = text.index("(\n", step3_idx)
    between = text[subshell_open_idx:marker_idx]
    assert between.strip().endswith("") or "_tel_dir=" not in between, (
        "the .allow-compact check must be the first statement inside the STEP 3 subshell"
    )


def _rotation_landmark_offsets(text: str) -> tuple[int, int, int]:
    """Return (hardlink_probe_offset, dot1_probe_offset, mv_offset), each the
    landmark's own first offset from position 0 (round-1 critic MAJ-1: never
    anchor relative to another landmark — that can pass tautologically)."""
    hardlink_probe = text.index('printf \'[quoin-precompact] WARNING: telemetry sink refused (hard link)')
    dot1_probe = text.index('[ -e "${_tel_sink}.1" ] || [ -L "${_tel_sink}.1" ]')
    mv_stmt = text.index('if ! mv -f "$_tel_sink" "${_tel_sink}.1"')
    tel_esc = text.index('_tel_esc=$(jq -nc --arg s "$session_id"')
    return hardlink_probe, dot1_probe, mv_stmt, tel_esc


def test_precompact_rotation_ordering_contract():
    text = _precompact_text()
    hardlink_probe, dot1_probe, mv_stmt, tel_esc = _rotation_landmark_offsets(text)
    assert hardlink_probe < dot1_probe < mv_stmt < tel_esc, (
        "rotation must sit after the hard-link refusal and before the "
        "_tel_esc session-id probe, with its own .1 probe ahead of the mv"
    )


# ─── mutation probe: rotation moved after _tel_esc ───────────────────────────


def test_mutation_probe_rotation_after_tel_esc_fails(tmp_path):
    """Move the rotation block after the _tel_esc line in a scratch copy and
    confirm the ordering assertion fails — a guard that still passes under
    the mutation is not pinning what it claims."""
    text = _precompact_text()
    block_start = text.index("  _tel_max=${TELEMETRY_MAX_BYTES:-1048576}")
    block_end = text.index('_tel_esc=$(jq -nc --arg s "$session_id"')
    rotation_block = text[block_start:block_end]
    tel_esc_line_end = text.index("\n", block_end) + 1
    tel_esc_line = text[block_end:tel_esc_line_end]

    mutated = text[:block_start] + tel_esc_line + rotation_block + text[tel_esc_line_end:]
    hardlink_probe, dot1_probe, mv_stmt, tel_esc = _rotation_landmark_offsets(mutated)
    assert not (hardlink_probe < dot1_probe < mv_stmt < tel_esc), (
        "mutation did not move rotation after _tel_esc as intended"
    )
