"""IVG-258 stage 5 T-05: compaction_telemetry.py reader unit tests.

Shape mirrors test_run_state_writer.py: subprocess the reader and the two
shell hooks against tmp_path, assert on stdout/JSON. No LLM calls.

Reader units run over sinks *generated by running the hooks* wherever
possible — a committed/hand-authored fixture is suspect until reproduced
end-to-end from the shipped code path (round-1 critic precedent). The
ambiguity fixture's second case is hand-authored by necessity (asserting a
same-file key collision the hooks themselves only produce once
QUOIN_TELEMETRY_MAX_BYTES is raised past the 1 MiB tail window).
"""
from __future__ import annotations

import json
import os
import subprocess
import sys
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[3]
READER = REPO_ROOT / "quoin" / "core" / "scripts" / "compaction_telemetry.py"
HOOK_PRE = REPO_ROOT / "quoin" / "hooks" / "precompact.sh"
HOOK_POST = REPO_ROOT / "quoin" / "hooks" / "postcompact.sh"
RUN_STATE = REPO_ROOT / "quoin" / "core" / "scripts" / "run_state.py"

PY = sys.executable


def _run_reader(project_root: Path, *extra_args, env=None) -> dict:
    full_env = dict(os.environ)
    if env:
        full_env.update(env)
    result = subprocess.run(
        [PY, str(READER), "--project-root", str(project_root), "--format", "json", *extra_args],
        capture_output=True,
        text=True,
        timeout=30,
        env=full_env,
    )
    assert result.returncode == 0, f"reader exited {result.returncode}: {result.stderr}"
    return json.loads(result.stdout)


def _make_stdin_pre(session_id: str, cwd: Path, trigger: str = "auto") -> str:
    return json.dumps(
        {
            "trigger": trigger,
            "session_id": session_id,
            "cwd": str(cwd),
            "transcript_path": str(cwd / "dummy.jsonl"),
        }
    )


def _make_stdin_post(session_id: str, cwd: Path, transcript: Path) -> str:
    return json.dumps(
        {
            "session_id": session_id,
            "cwd": str(cwd),
            "transcript_path": str(transcript),
            "hook_event_name": "PostCompact",
        }
    )


def _drive_pair(cwd: Path, session_id: str, transcript: Path, env=None) -> None:
    full_env = dict(os.environ)
    if env:
        full_env.update(env)
    subprocess.run(
        ["sh", str(HOOK_PRE)],
        input=_make_stdin_pre(session_id, cwd),
        capture_output=True,
        text=True,
        timeout=15,
        env=full_env,
    )
    subprocess.run(
        ["sh", str(HOOK_POST)],
        input=_make_stdin_post(session_id, cwd, transcript),
        capture_output=True,
        text=True,
        timeout=15,
        env=full_env,
    )


def _sink_path(project_root: Path) -> Path:
    return project_root / ".workflow_artifacts" / "memory" / "telemetry" / "compaction-events.jsonl"


# ─── reader units over hook-generated sinks ──────────────────────────────────


def test_reader_basic_pair_from_real_hooks(tmp_path):
    transcript = tmp_path / "dummy.jsonl"
    transcript.write_text('{"type":"message"}\n')
    _drive_pair(tmp_path, "sess-basic", transcript)

    report = _run_reader(tmp_path)
    assert report["matched"] == 1
    assert report["ambiguous"] == 0
    assert report["pre_only"] == 0
    assert report["post_only"] == 0
    assert report["malformed"] == 0
    assert report["pre"] == 1
    assert report["post"] == 1


def test_reader_truncated_line_counts_malformed(tmp_path):
    transcript = tmp_path / "dummy.jsonl"
    transcript.write_text('{"type":"message"}\n')
    _drive_pair(tmp_path, "sess-truncate", transcript)

    sink = _sink_path(tmp_path)
    lines = sink.read_text().splitlines()
    assert len(lines) == 2
    lines[0] = lines[0][: len(lines[0]) // 2]  # truncate the pre line mid-JSON
    sink.write_text("\n".join(lines) + "\n")

    report = _run_reader(tmp_path)
    assert report["malformed"] == 1
    assert report["pre"] == 0
    assert report["post"] == 1
    assert report["post_only"] == 1


def test_reader_missing_post_is_pre_only(tmp_path):
    transcript = tmp_path / "dummy.jsonl"
    transcript.write_text('{"type":"message"}\n')
